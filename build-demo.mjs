// Bundles the real full-screen UI (src/tui/demo.js) for the landing site's
// demo, so the demo is the app's own screen and keys. Writes site/lib/tui-demo.js.
// `npm test` fails when the committed bundle is out of date.
import { build } from 'esbuild';
import { fileURLToPath } from 'url';

export const OUT = fileURLToPath(new URL('./site/lib/tui-demo.js', import.meta.url));
const STUB = fileURLToPath(new URL('./src/tui/node-stub.js', import.meta.url));
const BANNER = '// Generated by `npm run build:demo` from src/tui/demo.js. Do not edit.\n/* eslint-disable */';

/** @param {boolean} write  false returns the bundle text instead of writing it */
export async function buildDemo(write = true) {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('./src/tui/demo.js', import.meta.url))],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    alias: { fs: STUB, path: STUB },
    banner: { js: BANNER },
    outfile: OUT,
    write,
    logLevel: write ? 'info' : 'silent',
  });
  return write ? null : result.outputFiles[0].text;
}

if (import.meta.url === `file://${process.argv[1]}`) await buildDemo();
